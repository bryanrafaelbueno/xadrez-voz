export const PIECE_NAMES = {
  pt: { P: 'peão', N: 'cavalo', B: 'bispo', R: 'torre', Q: 'dama', K: 'rei' },
  en: { P: 'pawn', N: 'knight', B: 'bishop', R: 'rook', Q: 'queen', K: 'king' },
};

export function t(lang, key, vars = {}) {
  const table = STRINGS[lang === 'en' ? 'en' : 'pt'];
  let value = table[key];
  if (value == null) value = STRINGS.pt[key] ?? key;
  if (typeof value === 'string') {
    return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] != null ? String(vars[name]) : `{${name}}`));
  }
  return value;
}

export function describeMove(move, lang = 'pt') {
  if (!move) return '';
  const l = lang === 'en' ? 'en' : 'pt';
  const names = PIECE_NAMES[l];
  const piece = names[move.piece] || '';
  const from = move.from;
  const to = move.to;
  let text;
  if (move.castle === 'k') text = l === 'en' ? 'Castle kingside' : 'Roque pequeno';
  else if (move.castle === 'q') text = l === 'en' ? 'Castle queenside' : 'Roque grande';
  else if (move.piece === 'P') {
    if (move.capture) text = l === 'en' ? `Pawn captures on ${to}` : `Peão captura em ${to}`;
    else text = l === 'en' ? `Pawn from ${from} to ${to}` : `Peão de ${from} para ${to}`;
    if (move.promotion) {
      const promo = names[move.promotion] || '';
      text += l === 'en' ? `, promoted to ${promo}` : `, promovido a ${promo}`;
    }
  } else if (move.capture) {
    text = l === 'en' ? `${capitalize(piece)} captures on ${to}` : `${capitalize(piece)} captura em ${to}`;
  } else {
    text = l === 'en' ? `${capitalize(piece)} from ${from} to ${to}` : `${capitalize(piece)} de ${from} para ${to}`;
  }
  if (move.san && move.san.includes('#')) text += l === 'en' ? ', checkmate' : ', xeque-mate';
  else if (move.san && move.san.includes('+')) text += l === 'en' ? ', check' : ', xeque';
  return text;
}

export function describeResult(status, lang = 'pt') {
  const l = lang === 'en' ? 'en' : 'pt';
  if (!status || !status.over) return '';
  if (status.reason === 'resign') return t(l, 'reasonResign');
  if (status.winner === 1) return t(l, 'resultWhiteWins');
  if (status.winner === -1) return t(l, 'resultBlackWins');
  const reasonKey = {
    stalemate: 'reasonStalemate',
    fifty: 'reasonFifty',
    repetition: 'reasonRepetition',
    material: 'reasonMaterial',
    checkmate: 'reasonCheckmate',
  }[status.reason];
  return reasonKey ? `${t(l, 'resultDraw')} ${t(l, reasonKey)}` : t(l, 'resultDraw');
}

export function describeStatus(status, lang = 'pt', turn = 1) {
  const l = lang === 'en' ? 'en' : 'pt';
  if (!status) return '';
  if (status.over) return describeResult(status, l);
  const sideName = turn === 1 ? t(l, 'white') : t(l, 'black');
  return t(l, status.check ? 'statusCheck' : 'statusTurn', { side: sideName });
}

function capitalize(value) {
  return value ? value[0].toUpperCase() + value.slice(1) : value;
}
